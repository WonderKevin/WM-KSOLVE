update location_dc_reference
set
  customer_key = pg_temp.normalize_location_key_part(customer),
  retailer_area_key = pg_temp.normalize_location_key_part(retailer_area);

create index location_dc_reference_key_idx
on location_dc_reference (customer_key, retailer_area_key);

create temporary table location_dc_matches on commit drop as
select
  l.id,
  l.customer as existing_customer,
  l.retailer_area as existing_retailer_area,
  l.dc as old_dc,
  r.dc as new_dc
from public.locations l
join location_dc_reference r
  on pg_temp.normalize_location_key_part(l.customer) = r.customer_key
 and pg_temp.normalize_location_key_part(l.retailer_area) = r.retailer_area_key;

create temporary table location_dc_unmatched on commit drop as
select r.customer, r.retailer_area, r.retailer, r.dc
from location_dc_reference r
where not exists (
  select 1
  from public.locations l
  where pg_temp.normalize_location_key_part(l.customer) = r.customer_key
    and pg_temp.normalize_location_key_part(l.retailer_area) = r.retailer_area_key
);

select
  (select count(*) from location_dc_reference) as workbook_locations,
  (select count(*) from location_dc_matches) as matched_locations,
  (select count(*) from location_dc_matches where old_dc is distinct from new_dc) as locations_to_change,
  (select count(*) from location_dc_unmatched) as locations_to_insert;

update public.locations l
set dc = m.new_dc
from location_dc_matches m
where l.id = m.id
  and l.dc is distinct from m.new_dc;

select
  count(*) filter (where old_dc is distinct from new_dc) as updated_locations,
  count(*) as matched_locations
from location_dc_matches;

with inserted as (
  insert into public.locations (customer, retailer_area, retailer, dc)
  select customer, retailer_area, retailer, dc
  from location_dc_unmatched
  returning id
)
select count(*) as inserted_locations
from inserted;

select customer, retailer_area, retailer, dc
from location_dc_unmatched
order by retailer_area, customer;

commit;
